// Language Manager Class
class LanguageManager {
    constructor() {
        this.currentLang = localStorage.getItem('preferredLanguage') || 'th';
        this.eventBound = false;
        this.init();
    }
    
    init() {
        // Set initial language
        this.setLanguage(this.currentLang);
        
        // Add language switcher to navigation
        this.addLanguageSwitcher();
        
        // Update page content
        this.updateContent();
    }
    
    addLanguageSwitcher() {
        // Use setTimeout to ensure header is fully loaded
        setTimeout(() => {
            const langToggle = document.querySelector('.lang-toggle');
            
            if (langToggle && !this.eventBound) {
                // Update the language text
                const langText = langToggle.querySelector('.lang-text');
                if (langText) {
                    langText.textContent = this.currentLang.toUpperCase();
                }
                
                // Remove any existing event listeners by cloning
                const newLangToggle = langToggle.cloneNode(true);
                langToggle.parentNode.replaceChild(newLangToggle, langToggle);
                
                // Add click event listener
                newLangToggle.addEventListener('click', (e) => {
                    e.preventDefault();
                    console.log('Language toggle clicked!');
                    this.toggleLanguage();
                });
                
                this.eventBound = true;
                console.log('✓ Language switcher initialized successfully');
            } else if (!langToggle) {
                console.warn('⚠ Language toggle button not found in DOM');
            } else {
                console.log('Language switcher already bound');
            }
        }, 100);
    }
    
    // Reinitialize method for when header is loaded dynamically
    reinit() {
        this.eventBound = false;
        this.addLanguageSwitcher();
        this.updateContent();
    }
    
    setLanguage(lang) {
        this.currentLang = lang;
        localStorage.setItem('preferredLanguage', lang);
        document.documentElement.setAttribute('lang', lang);
        
        // Update language toggle text
        const langText = document.querySelector('.lang-text');
        if (langText) {
            langText.textContent = lang.toUpperCase();
        }
    }
    
    toggleLanguage() {
        const newLang = this.currentLang === 'th' ? 'en' : 'th';
        console.log(`Switching language from ${this.currentLang} to ${newLang}`);
        this.setLanguage(newLang);
        this.updateContent();
        console.log('✓ Language switched successfully');
    }
    
    getTranslation(key) {
        const keys = key.split('.');
        let value = translations[this.currentLang];
        
        for (const k of keys) {
            value = value[k];
            if (!value) return key;
        }
        
        return value;
    }
    
    updateContent() {
        // Update all elements with data-i18n attribute
        const elements = document.querySelectorAll('[data-i18n]');
        console.log(`Updating ${elements.length} elements with language: ${this.currentLang}`);
        
        elements.forEach(element => {
            const key = element.getAttribute('data-i18n');
            const translation = this.getTranslation(key);
            
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translation;
            } else {
                element.textContent = translation;
            }
        });
        
        // Update page title
        const pageTitle = document.querySelector('[data-i18n-title]');
        if (pageTitle) {
            const key = pageTitle.getAttribute('data-i18n-title');
            document.title = this.getTranslation(key);
        }
        
        // Update lang text in button
        const langText = document.querySelector('.lang-text');
        if (langText) {
            langText.textContent = this.currentLang.toUpperCase();
        }
    }
}

// Initialize language manager when DOM is ready
document.addEventListener('DOMContentLoaded', function() {
    window.langManager = new LanguageManager();
});

// Listen for header load event from components.js
document.addEventListener('componentLoaded', function(event) {
    if (event.detail.name === 'header' && window.langManager) {
        console.log('Header loaded, reinitializing language switcher');
        window.langManager.reinit();
    }
});

// Global function to reinitialize language (called by components.js)
window.initLanguage = function() {
    if (window.langManager) {
        console.log('initLanguage called, reinitializing...');
        window.langManager.reinit();
    } else {
        console.log('Creating new LanguageManager...');
        window.langManager = new LanguageManager();
    }
};

// Export for use in other scripts
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { LanguageManager, translations };
}

